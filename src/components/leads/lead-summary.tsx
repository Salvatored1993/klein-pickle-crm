import { formatCurrency, formatDate, productLabel } from "@/lib/format";
import { COMPANY_FACILITY_ADDRESS } from "@/lib/constants";
import type { Database } from "@/lib/database.types";
import type { LeadProductLineItem } from "@/app/(app)/leads/actions";

type Lead = Database["public"]["Views"]["leads_with_totals"]["Row"];
type Tone = "print" | "app";

// Read-only summary of everything captured on a lead. Used by the printable
// lead page and by a converted customer's "Lead info" tab.
const TONES = {
  print: {
    label: "text-neutral-500",
    value: "text-neutral-900",
    border: "border-neutral-200",
    heading: "text-neutral-700",
    muted: "text-neutral-500",
    tableHead: "border-neutral-300 text-neutral-500",
    tableRow: "border-neutral-100",
  },
  app: {
    label: "text-muted-foreground",
    value: "text-foreground",
    border: "border-border",
    heading: "text-foreground",
    muted: "text-muted-foreground",
    tableHead: "border-border text-muted-foreground",
    tableRow: "border-border",
  },
} as const;

type ToneClasses = (typeof TONES)[Tone];

function Field({ t, label, value }: { t: ToneClasses; label: string; value: React.ReactNode }) {
  return (
    <div className="flex flex-col gap-0.5">
      <dt className={`text-xs uppercase tracking-wide ${t.label}`}>{label}</dt>
      <dd className={`text-sm whitespace-pre-wrap ${t.value}`}>{value || "—"}</dd>
    </div>
  );
}

function Section({
  t,
  title,
  children,
}: {
  t: ToneClasses;
  title: string;
  children: React.ReactNode;
}) {
  return (
    <section
      className={`break-inside-avoid border-t py-4 first:border-none first:pt-0 ${t.border}`}
    >
      <h2 className={`mb-3 text-sm font-semibold uppercase tracking-wide ${t.heading}`}>{title}</h2>
      <dl className="grid grid-cols-2 gap-x-6 gap-y-3">{children}</dl>
    </section>
  );
}

function lineItemName(
  item: LeadProductLineItem,
  products: { id: string; item_number: string; name: string }[],
) {
  if (item.productId) {
    const product = products.find((p) => p.id === item.productId);
    return product ? productLabel(product) : "Unknown product";
  }
  return `${item.customProductName ?? "Custom product"} (Custom)`;
}

export function LeadSummary({
  lead,
  lineItems,
  products,
  salespersonName,
  tone = "app",
}: {
  lead: Lead;
  lineItems: LeadProductLineItem[];
  products: { id: string; item_number: string; name: string }[];
  salespersonName: string;
  tone?: Tone;
}) {
  const t = TONES[tone];

  return (
    <div>
      <Section t={t} title="Basic info">
        <Field t={t} label="Salesperson / lead generated by" value={salespersonName} />
        <Field t={t} label="Primary contact" value={lead.primary_contact_name} />
        <Field t={t} label="Contact email" value={lead.contact_email} />
        <Field t={t} label="Contact phone" value={lead.contact_phone} />
        <Field t={t} label="Date lead created" value={formatDate(lead.lead_date)} />
        <Field t={t} label="Lead source" value={lead.lead_source} />
        <Field t={t} label="Specific source" value={lead.specific_source} />
      </Section>

      <Section t={t} title="Opportunity details">
        <Field t={t} label="Customer type" value={lead.customer_type} />
      </Section>

      <section className={`break-inside-avoid border-t py-4 ${t.border}`}>
        <h2 className={`mb-3 text-sm font-semibold uppercase tracking-wide ${t.heading}`}>
          Products interested in &amp; sizes
        </h2>
        {lineItems.length > 0 ? (
          <table className="w-full border-collapse text-sm">
            <thead>
              <tr className={`border-b text-left text-xs uppercase tracking-wide ${t.tableHead}`}>
                <th className="py-1 pr-2">Product</th>
                <th className="py-1 pr-2">Pack size(s)</th>
                <th className="py-1 pr-2">Proposed vol.</th>
                <th className="py-1 pr-2">Est. annual vol.</th>
                <th className="py-1 pr-2">Est. annual sales</th>
                <th className="py-1 pr-2">Target price</th>
                <th className="py-1">Specs</th>
              </tr>
            </thead>
            <tbody>
              {lineItems.map((item, index) => {
                const sizeLabel =
                  item.packSizes.length > 0
                    ? item.packSizes
                        .map((s) =>
                          s === "Other" && item.customPackSize
                            ? `Other (${item.customPackSize})`
                            : s,
                        )
                        .join(", ")
                    : "—";
                return (
                  <tr key={index} className={`border-b align-top ${t.tableRow}`}>
                    <td className="py-1.5 pr-2 font-medium">{lineItemName(item, products)}</td>
                    <td className="py-1.5 pr-2">{sizeLabel}</td>
                    <td className="py-1.5 pr-2">
                      {item.proposedVolume
                        ? `${item.proposedVolume} ${item.volumeUnit ?? "units"}`
                        : "—"}
                    </td>
                    <td className="py-1.5 pr-2">
                      {item.estimatedAnnualVolume
                        ? `${item.estimatedAnnualVolume} ${item.volumeUnit ?? "units"}/yr`
                        : "—"}
                    </td>
                    <td className="py-1.5 pr-2">{formatCurrency(item.estimatedAnnualSales)}</td>
                    <td className="py-1.5 pr-2">{formatCurrency(item.targetPrice)}</td>
                    <td className="py-1.5">{item.customSpecs || "—"}</td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        ) : (
          <p className={`text-sm ${t.muted}`}>No products added.</p>
        )}
      </section>

      <Section t={t} title="Commercial terms">
        <Field t={t} label="Freight terms" value={lead.freight_terms} />
        <Field t={t} label="Distributor" value={lead.distributor} />
        {lead.freight_terms === "FOB Origin" ? (
          <Field
            t={t}
            label="Ship-to"
            value={`Klein Pickle facility — ${COMPANY_FACILITY_ADDRESS}`}
          />
        ) : (
          <Field
            t={t}
            label="Ship-to address"
            value={[
              lead.ship_to_address,
              lead.ship_to_city,
              lead.ship_to_state,
              lead.ship_to_zip,
              lead.ship_to_country,
            ]
              .filter(Boolean)
              .join(", ")}
          />
        )}
        <Field t={t} label="Broker involved" value={lead.broker_involved ? "Yes" : "No"} />
        {lead.broker_involved ? (
          <>
            <Field t={t} label="Broker name" value={lead.broker_name} />
            <Field t={t} label="Broker company" value={lead.broker_company} />
            <Field
              t={t}
              label="Broker commission"
              value={lead.broker_commission_pct !== null ? `${lead.broker_commission_pct}%` : null}
            />
          </>
        ) : null}
      </Section>

      <Section t={t} title="Sample & competitive landscape">
        <Field t={t} label="Sample required" value={lead.sample_required ? "Yes" : "No"} />
        <Field t={t} label="Sample / trial status" value={lead.sample_trial_status} />
        <Field t={t} label="Current supplier" value={lead.current_supplier} />
        <Field t={t} label="Expected start date" value={formatDate(lead.expected_start_date)} />
        <div className="col-span-2">
          <Field t={t} label="Reason for opportunity" value={lead.reason_for_opportunity} />
        </div>
      </Section>

      <Section t={t} title="Stage & follow-up">
        <Field t={t} label="Sales stage" value={lead.sales_stage} />
        <Field
          t={t}
          label="Probability to close"
          value={lead.probability_to_close !== null ? `${lead.probability_to_close}%` : null}
        />
        <Field t={t} label="Next action" value={lead.next_action} />
        <Field t={t} label="Next follow-up date" value={formatDate(lead.next_follow_up_date)} />
        {lead.sales_stage === "Lost" ? (
          <div className="col-span-2">
            <Field t={t} label="Lost reason" value={lead.lost_reason} />
          </div>
        ) : null}
        <div className="col-span-2">
          <Field t={t} label="Notes / requirements" value={lead.notes} />
        </div>
      </Section>
    </div>
  );
}
